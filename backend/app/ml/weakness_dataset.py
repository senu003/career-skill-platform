"""
WEAKNESS ML DATASET BUILDER MODULE

Transforms candidate assessment attempts into a clean, ML-ready dataset
by combining feature vectors extracted via build_weakness_features with target labels
computed via compute_weakness_target_label.

Preserves 'skill' as metadata and avoids using it as a raw numerical ML feature.
Does NOT modify database records or input attempt data.
"""

from typing import List, Dict, Any, Union, Optional, Tuple
import pandas as pd

from app.ml.weakness_features import build_weakness_features, FEATURE_KEYS
from app.ml.weakness_labels import compute_weakness_target_label, TARGET_LABEL_KEY

# Metadata fields that identify records but are not raw numeric features
METADATA_KEYS: List[str] = ["skill", "candidate_id", "attempt_id", "user_id"]

# Pure numerical ML feature keys (17 features)
NUMERICAL_FEATURE_KEYS: List[str] = [k for k in FEATURE_KEYS if k not in METADATA_KEYS]


def build_weakness_dataset(
    attempts: List[Union[Dict[str, Any], Any]],
    target_key: str = TARGET_LABEL_KEY
) -> List[Dict[str, Any]]:
    """
    Builds a clean tabular Python dataset from assessment attempts.

    Parameters:
        attempts (list): List of assessment attempt dicts or AssessmentAttempt ORM objects.
        target_key (str): Key name for the target label in each record. Default "is_weakness".

    Returns:
        list of dicts: List of dataset records, one per assessed skill. Each record contains
                       all 18 feature keys from FEATURE_KEYS plus the target label key.
    """
    if not isinstance(attempts, list) or not attempts:
        return []

    # 1. Reuse existing feature extractor (does not mutate inputs)
    feature_records = build_weakness_features(attempts)

    # 2. Attach target label to each record without mutating feature_records
    dataset: List[Dict[str, Any]] = []
    for record in feature_records:
        new_record = record.copy()
        target_val = compute_weakness_target_label(record)
        new_record[target_key] = target_val
        dataset.append(new_record)

    return dataset


def build_weakness_dataset_dataframe(
    attempts: List[Union[Dict[str, Any], Any]],
    target_key: str = TARGET_LABEL_KEY
) -> pd.DataFrame:
    """
    Builds a pandas DataFrame training dataset from assessment attempts.

    Parameters:
        attempts (list): List of assessment attempt dicts or AssessmentAttempt ORM objects.
        target_key (str): Key name for the target label column. Default "is_weakness".

    Returns:
        pd.DataFrame: DataFrame containing feature columns, skill metadata, and target label.
    """
    records = build_weakness_dataset(attempts, target_key=target_key)
    if not records:
        columns = list(FEATURE_KEYS) + [target_key]
        return pd.DataFrame(columns=columns)
    
    df = pd.DataFrame(records)
    # Ensure explicit column ordering: 18 features + target_key
    column_order = list(FEATURE_KEYS) + [target_key]
    return df[column_order]


def extract_X_y(
    dataset: List[Dict[str, Any]],
    target_key: str = TARGET_LABEL_KEY
) -> Tuple[List[Dict[str, Any]], List[int], List[str]]:
    """
    Separates dataset into numerical feature dicts (X), target labels (y), and skill metadata.

    Parameters:
        dataset (list of dicts): Dataset generated by build_weakness_dataset.
        target_key (str): Key name for the target label.

    Returns:
        Tuple (X_features, y_labels, metadata_skills):
          - X_features: list of dicts with only numerical features (no 'skill' or target_key).
          - y_labels: list of int target labels (0 or 1).
          - metadata_skills: list of str skill names.
    """
    X_features: List[Dict[str, Any]] = []
    y_labels: List[int] = []
    metadata_skills: List[str] = []

    for row in dataset:
        skill_meta = str(row.get("skill", ""))
        label_val = int(row.get(target_key, 0))

        num_feats = {k: row[k] for k in NUMERICAL_FEATURE_KEYS if k in row}

        X_features.append(num_feats)
        y_labels.append(label_val)
        metadata_skills.append(skill_meta)

    return X_features, y_labels, metadata_skills
